-- 08_blackboard/sql/99_teardown.sql
-- Delete only pattern 08 objects. Suspend and drop tasks before streams, views, procedures, and tables.
-- Proposals copied from the board to the common PROPOSED_ACTIONS table remain.

USE ROLE ACCOUNTADMIN;

ALTER TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_DECOMPOSE SUSPEND;
ALTER TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_DEDUPE SUSPEND;
ALTER TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_CRITERIA SUSPEND;
ALTER TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_ASSEMBLE SUSPEND;
DROP TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_DECOMPOSE;
DROP TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_DEDUPE;
DROP TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_CRITERIA;
DROP TASK IF EXISTS <% db %>.INTERNAL.BOARD_T_ASSEMBLE;
DROP STREAM IF EXISTS <% db %>.INTERNAL.BOARD_S_DECOMPOSE;
DROP VIEW IF EXISTS <% db %>.INTERNAL.BOARD_V_DECOMPOSE;
DROP STREAM IF EXISTS <% db %>.INTERNAL.BOARD_S_DEDUPE;
DROP VIEW IF EXISTS <% db %>.INTERNAL.BOARD_V_DEDUPE;
DROP STREAM IF EXISTS <% db %>.INTERNAL.BOARD_S_CRITERIA;
DROP VIEW IF EXISTS <% db %>.INTERNAL.BOARD_V_CRITERIA;
DROP STREAM IF EXISTS <% db %>.INTERNAL.BOARD_S_ASSEMBLE;
DROP VIEW IF EXISTS <% db %>.INTERNAL.BOARD_V_ASSEMBLE;
DROP PROCEDURE IF EXISTS <% db %>.APP.POST_MEETING_NOTE(STRING);
DROP PROCEDURE IF EXISTS <% db %>.INTERNAL.BOARD_REACT(STRING);
DROP VIEW IF EXISTS <% db %>.APP.V_BOARD_TIMELINE;
DROP VIEW IF EXISTS <% db %>.APP.V_BOARD_INBOX;
DROP TABLE IF EXISTS <% db %>.INTERNAL.BOARD_INBOX;
DROP TABLE IF EXISTS <% db %>.INTERNAL.BOARD_ITEMS;
