#!/usr/bin/env python3
"""
ML の特徴量テーブルを作るスクリプト

ml_pipeline_v3.py の前に実行する。v3 は学習データを
HR_ANALYTICS.PUBLIC の次のテーブルから読むため、先にここで作っておく:
- ATTRITION_FEATURES      離職予測の特徴量（在籍中の社員ごと）
- RELATIONSHIP_FEATURES   上長と部下の関係性の特徴量（ペアごと）
- DEPT_CULTURE_VECTORS    部署ごとの雰囲気（1on1 の感情平均）
- TRANSFER_FIT_FEATURES   異動先候補との適合度の特徴量（社員 × 空きポスト）

入力は STAGING の同期済みテーブルと、scripts/generate_ml_inputs.py で作ったテーブル。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from session_util import create_session

session = create_session()
session.use_database("HR_ANALYTICS")
session.use_warehouse("HR_AI_WH")
session.use_schema("PUBLIC")

# ============================================================================
# STEP 1: Feature Engineering (Phase 1-1 fix + Phase 2-2 design features)
# ============================================================================
print("\n--- Step 1: Feature Engineering ---")

# 1a. ATTRITION FEATURES — corrected column names + design doc features A1-A10
print("  Computing ATTRITION_FEATURES (v2)...")
session.sql("DELETE FROM ATTRITION_FEATURES").collect()
session.sql("""
INSERT INTO ATTRITION_FEATURES
    (EMPLOYEE_ID, TENURE_MONTHS, AVG_EVAL_SCORE, EVAL_TREND,
     RISK_SIGNAL_COUNT, CAREER_CHANGE_COUNT, SENTIMENT_AVG, SENTIMENT_TREND,
     MONTHS_SINCE_PROMOTION, TEAM_SIZE, PREVIOUS_COMPANY_COUNT,
     COMMUTE_TIME_MINUTES, SELF_EVAL_GAP, PEER_COLLAB_SCORE,
     EVAL_CATEGORY_LATEST, DEPT_ID, COMPUTED_AT)
WITH emp_base AS (
    SELECT e.EMPLOYEE_ID, e.DEPT_ID, e.MANAGER_ID,
           DATEDIFF('month', e.HIRE_DATE, CURRENT_DATE()) AS TENURE_MONTHS,
           DATEDIFF('month', COALESCE(e.LAST_PROMOTION_DATE, e.HIRE_DATE), CURRENT_DATE()) AS MONTHS_SINCE_PROMO,
           COALESCE(e.COMMUTE_TIME_MINUTES, 30) AS COMMUTE,
           COALESCE(ep.PREVIOUS_COMPANY_COUNT, 0) AS PREV_COMPANIES
    FROM HR_ANALYTICS.STAGING.EMPLOYEES e
    LEFT JOIN HR_ANALYTICS.STAGING.EMPLOYEE_PROFILES ep ON e.EMPLOYEE_ID = ep.EMPLOYEE_ID
    WHERE e.STATUS = 'active'
),
eval_numbered AS (
    SELECT EMPLOYEE_ID, SCORE, SELF_SCORE,
           ROW_NUMBER() OVER (PARTITION BY EMPLOYEE_ID ORDER BY PERIOD) AS RN
    FROM HR_ANALYTICS.STAGING.EVALUATIONS
),
eval_stats AS (
    SELECT EMPLOYEE_ID,
           AVG(SCORE) AS AVG_SCORE,
           REGR_SLOPE(SCORE, RN) AS EVAL_TREND_SLOPE,
           AVG(SCORE - SELF_SCORE) AS SELF_GAP
    FROM eval_numbered GROUP BY EMPLOYEE_ID
),
note_numbered AS (
    SELECT oa.EMPLOYEE_ID, oa.SENTIMENT_SCORE,
           ROW_NUMBER() OVER (PARTITION BY oa.EMPLOYEE_ID ORDER BY n.NOTE_DATE) AS RN
    FROM HR_ANALYTICS.STAGING.ONEONONE_ANALYSIS oa
    JOIN HR_ANALYTICS.STAGING.ONE_ON_ONE_NOTES n ON oa.NOTE_ID = n.NOTE_ID
),
note_stats AS (
    SELECT EMPLOYEE_ID, AVG(SENTIMENT_SCORE) AS SENT_AVG, REGR_SLOPE(SENTIMENT_SCORE, RN) AS SENT_TREND
    FROM note_numbered GROUP BY EMPLOYEE_ID
),
risk_counts AS (
    SELECT EMPLOYEE_ID, COUNT(*) AS RISK_CNT
    FROM HR_ANALYTICS.STAGING.ONEONONE_ANALYSIS
    WHERE RISK_SIGNALS IS NOT NULL AND ARRAY_SIZE(RISK_SIGNALS) > 0
    GROUP BY EMPLOYEE_ID
),
career_stats AS (
    SELECT EMPLOYEE_ID, COUNT(*) AS TRANSFER_COUNT
    FROM HR_ANALYTICS.STAGING.CAREER_HISTORY
    WHERE TRANSFER_TYPE != 'hire'
    GROUP BY EMPLOYEE_ID
),
team_sizes AS (
    SELECT MANAGER_ID, COUNT(*) AS TEAM_SIZE
    FROM HR_ANALYTICS.STAGING.EMPLOYEES WHERE STATUS = 'active' AND MANAGER_ID IS NOT NULL
    GROUP BY MANAGER_ID
),
peer_collab AS (
    SELECT EMPLOYEE_ID, AVG(COLLABORATION_SCORE) AS AVG_COLLAB
    FROM HR_ANALYTICS.STAGING.PEER_FEEDBACK
    GROUP BY EMPLOYEE_ID
),
eval_cat_latest AS (
    SELECT ea.EMPLOYEE_ID, ea.CATEGORY
    FROM HR_ANALYTICS.STAGING.EVALUATION_ANALYSIS ea
    INNER JOIN (
        SELECT EMPLOYEE_ID, MAX(EVALUATION_ID) AS MAX_EID
        FROM HR_ANALYTICS.STAGING.EVALUATION_ANALYSIS GROUP BY EMPLOYEE_ID
    ) latest ON ea.EMPLOYEE_ID = latest.EMPLOYEE_ID AND ea.EVALUATION_ID = latest.MAX_EID
)
SELECT
    eb.EMPLOYEE_ID,
    eb.TENURE_MONTHS,
    COALESCE(es.AVG_SCORE, 3.0),
    COALESCE(es.EVAL_TREND_SLOPE, 0.0),
    COALESCE(rc.RISK_CNT, 0),
    COALESCE(cs.TRANSFER_COUNT, 0),
    COALESCE(ns.SENT_AVG, 0.0),
    COALESCE(ns.SENT_TREND, 0.0),
    eb.MONTHS_SINCE_PROMO,
    COALESCE(ts.TEAM_SIZE, 1),
    eb.PREV_COMPANIES,
    eb.COMMUTE,
    COALESCE(es.SELF_GAP, 0.0),
    COALESCE(pc.AVG_COLLAB, 3.0),
    -- v3 の Feature Store と同じ数値化（critical=0 / declining=1 / stable=2 / growth=3）
    CASE COALESCE(ecl.CATEGORY, 'stable')
        WHEN 'critical' THEN 0 WHEN 'declining' THEN 1 WHEN 'stable' THEN 2 WHEN 'growth' THEN 3 ELSE 2
    END,
    eb.DEPT_ID,
    CURRENT_TIMESTAMP()
FROM emp_base eb
LEFT JOIN eval_stats es ON eb.EMPLOYEE_ID = es.EMPLOYEE_ID
LEFT JOIN note_stats ns ON eb.EMPLOYEE_ID = ns.EMPLOYEE_ID
LEFT JOIN risk_counts rc ON eb.EMPLOYEE_ID = rc.EMPLOYEE_ID
LEFT JOIN career_stats cs ON eb.EMPLOYEE_ID = cs.EMPLOYEE_ID
LEFT JOIN team_sizes ts ON eb.MANAGER_ID = ts.MANAGER_ID
LEFT JOIN peer_collab pc ON eb.EMPLOYEE_ID = pc.EMPLOYEE_ID
LEFT JOIN eval_cat_latest ecl ON eb.EMPLOYEE_ID = ecl.EMPLOYEE_ID
""").collect()
att_count = session.sql("SELECT COUNT(*) AS C FROM ATTRITION_FEATURES").collect()[0]["C"]
print(f"  ATTRITION_FEATURES: {att_count} rows")

# 1b. RELATIONSHIP FEATURES — corrected column names
print("  Computing RELATIONSHIP_FEATURES (v2)...")
session.sql("DELETE FROM RELATIONSHIP_FEATURES").collect()
session.sql("""
INSERT INTO RELATIONSHIP_FEATURES
    (MANAGER_ID, EMPLOYEE_ID, ONEONONE_FREQ, ONEONONE_SENTIMENT_AVG,
     ONEONONE_SENTIMENT_TREND, ONEONONE_CATEGORY_DIST, EVAL_COMMENT_SENTIMENT,
     EVAL_SCORE_TREND, EVAL_GAP, PAIR_TENURE_MONTHS, SPAN_OF_CONTROL,
     AGE_DIFF, SUBORDINATE_LEADERSHIP_SCORE, SUBORDINATE_COMMUNICATION_SCORE, COMPUTED_AT)
WITH pairs AS (
    SELECT e.EMPLOYEE_ID, e.MANAGER_ID, e.DEPT_ID, e.HIRE_DATE, e.BIRTH_DATE
    FROM HR_ANALYTICS.STAGING.EMPLOYEES e
    WHERE e.STATUS = 'active' AND e.MANAGER_ID IS NOT NULL
),
mgr_info AS (
    SELECT EMPLOYEE_ID, HIRE_DATE AS MGR_HIRE, BIRTH_DATE AS MGR_BIRTH
    FROM HR_ANALYTICS.STAGING.EMPLOYEES
),
note_numbered2 AS (
    SELECT oa.EMPLOYEE_ID, oa.MANAGER_ID, oa.SENTIMENT_SCORE,
           ROW_NUMBER() OVER (PARTITION BY oa.EMPLOYEE_ID, oa.MANAGER_ID ORDER BY n.NOTE_DATE) AS RN
    FROM HR_ANALYTICS.STAGING.ONEONONE_ANALYSIS oa
    JOIN HR_ANALYTICS.STAGING.ONE_ON_ONE_NOTES n ON oa.NOTE_ID = n.NOTE_ID
),
note_agg AS (
    SELECT EMPLOYEE_ID, MANAGER_ID, COUNT(*) AS NOTE_CNT,
           AVG(SENTIMENT_SCORE) AS AVG_SENT, REGR_SLOPE(SENTIMENT_SCORE, RN) AS SENT_TREND
    FROM note_numbered2 GROUP BY EMPLOYEE_ID, MANAGER_ID
),
eval_numbered_r AS (
    SELECT EMPLOYEE_ID, EVALUATOR_ID, SCORE,
           ROW_NUMBER() OVER (PARTITION BY EMPLOYEE_ID, EVALUATOR_ID ORDER BY PERIOD) AS RN
    FROM HR_ANALYTICS.STAGING.EVALUATIONS
    WHERE EVALUATOR_ID IS NOT NULL
),
eval_agg AS (
    SELECT EMPLOYEE_ID, EVALUATOR_ID,
           AVG(SCORE) AS AVG_EVAL,
           AVG(SCORE - (SELECT AVG(SELF_SCORE) FROM HR_ANALYTICS.STAGING.EVALUATIONS e2 WHERE e2.EMPLOYEE_ID = eval_numbered_r.EMPLOYEE_ID)) AS AVG_GAP,
           REGR_SLOPE(SCORE, RN) AS EVAL_TREND
    FROM eval_numbered_r
    GROUP BY EMPLOYEE_ID, EVALUATOR_ID
),
peer_sub AS (
    SELECT EMPLOYEE_ID, AVG(LEADERSHIP_SCORE) AS SUB_LEAD, AVG(COMMUNICATION_SCORE) AS SUB_COMM
    FROM HR_ANALYTICS.STAGING.PEER_FEEDBACK
    WHERE REVIEWER_RELATION = 'subordinate'
    GROUP BY EMPLOYEE_ID
),
span AS (
    SELECT MANAGER_ID, COUNT(*) AS SPAN
    FROM HR_ANALYTICS.STAGING.EMPLOYEES WHERE STATUS='active' AND MANAGER_ID IS NOT NULL
    GROUP BY MANAGER_ID
)
SELECT
    p.MANAGER_ID,
    p.EMPLOYEE_ID,
    COALESCE(na.NOTE_CNT, 0) / GREATEST(DATEDIFF('month', p.HIRE_DATE, CURRENT_DATE()), 1),
    COALESCE(na.AVG_SENT, 0.0),
    COALESCE(na.SENT_TREND, 0.0),
    NULL,
    COALESCE(ea.AVG_EVAL, 3.0) / 5.0,
    COALESCE(ea.EVAL_TREND, 0.0),
    COALESCE(ea.AVG_GAP, 0.0),
    DATEDIFF('month', GREATEST(p.HIRE_DATE, COALESCE(mi.MGR_HIRE, p.HIRE_DATE)), CURRENT_DATE()),
    COALESCE(sp.SPAN, 1),
    ABS(DATEDIFF('year', p.BIRTH_DATE, COALESCE(mi.MGR_BIRTH, p.BIRTH_DATE))),
    COALESCE(ps.SUB_LEAD, 3.0) / 5.0,
    COALESCE(ps.SUB_COMM, 3.0) / 5.0,
    CURRENT_TIMESTAMP()
FROM pairs p
LEFT JOIN mgr_info mi ON p.MANAGER_ID = mi.EMPLOYEE_ID
LEFT JOIN note_agg na ON p.EMPLOYEE_ID = na.EMPLOYEE_ID AND p.MANAGER_ID = na.MANAGER_ID
LEFT JOIN eval_agg ea ON p.EMPLOYEE_ID = ea.EMPLOYEE_ID AND p.MANAGER_ID = ea.EVALUATOR_ID
LEFT JOIN peer_sub ps ON p.MANAGER_ID = ps.EMPLOYEE_ID
LEFT JOIN span sp ON p.MANAGER_ID = sp.MANAGER_ID
""").collect()
rel_count = session.sql("SELECT COUNT(*) AS C FROM RELATIONSHIP_FEATURES").collect()[0]["C"]
print(f"  RELATIONSHIP_FEATURES: {rel_count} rows")

# 1c. DEPT_CULTURE_VECTORS (Phase 3-4)
print("  Computing DEPT_CULTURE_VECTORS...")
session.sql("DELETE FROM DEPT_CULTURE_VECTORS").collect()
session.sql("""
INSERT INTO DEPT_CULTURE_VECTORS (DEPT_ID, AVG_SENTIMENT, DOMINANT_THEMES, COMPUTED_AT)
WITH dept_sentiment AS (
    SELECT e.DEPT_ID,
           AVG(oa.SENTIMENT_SCORE) AS AVG_SENT
    FROM HR_ANALYTICS.STAGING.ONEONONE_ANALYSIS oa
    JOIN HR_ANALYTICS.STAGING.EMPLOYEES e ON oa.EMPLOYEE_ID = e.EMPLOYEE_ID
    GROUP BY e.DEPT_ID
),
dept_eval AS (
    SELECT e.DEPT_ID,
           AVG(ev.SCORE) AS AVG_EVAL,
           AVG(pf.COLLABORATION_SCORE) AS AVG_COLLAB,
           AVG(pf.LEADERSHIP_SCORE) AS AVG_LEAD
    FROM HR_ANALYTICS.STAGING.EMPLOYEES e
    LEFT JOIN HR_ANALYTICS.STAGING.EVALUATIONS ev ON e.EMPLOYEE_ID = ev.EMPLOYEE_ID
    LEFT JOIN HR_ANALYTICS.STAGING.PEER_FEEDBACK pf ON e.EMPLOYEE_ID = pf.EMPLOYEE_ID
    GROUP BY e.DEPT_ID
)
SELECT d.DEPT_ID,
       COALESCE(ds.AVG_SENT, 0),
       OBJECT_CONSTRUCT(
           'avg_eval', ROUND(COALESCE(de.AVG_EVAL, 3.0), 2),
           'avg_collab', ROUND(COALESCE(de.AVG_COLLAB, 3.0), 2),
           'avg_leadership', ROUND(COALESCE(de.AVG_LEAD, 3.0), 2),
           'avg_sentiment', ROUND(COALESCE(ds.AVG_SENT, 0), 3)
       ),
       CURRENT_TIMESTAMP()
FROM HR_ANALYTICS.STAGING.DEPARTMENTS d
LEFT JOIN dept_sentiment ds ON d.DEPT_ID = ds.DEPT_ID
LEFT JOIN dept_eval de ON d.DEPT_ID = de.DEPT_ID
""").collect()
dcv_count = session.sql("SELECT COUNT(*) AS C FROM DEPT_CULTURE_VECTORS").collect()[0]["C"]
print(f"  DEPT_CULTURE_VECTORS: {dcv_count} rows")

# 1d. TRANSFER_FIT_FEATURES (Phase 3-1)
print("  Computing TRANSFER_FIT_FEATURES...")
session.sql("DELETE FROM TRANSFER_FIT_FEATURES").collect()
session.sql("""
INSERT INTO TRANSFER_FIT_FEATURES
    (EMPLOYEE_ID, TARGET_DEPT_ID, TARGET_POSITION_ID, SKILL_MATCH_RATE,
     SKILL_GAP_COUNT, TRANSFER_COUNT, TARGET_AVG_TENURE, MGR_RELATIONSHIP_SCORE,
     EVAL_TREND, CULTURE_SIMILARITY, GRADE_DIFF, AGE, SENTIMENT_TREND, COMPUTED_AT)
WITH active_emps AS (
    SELECT e.EMPLOYEE_ID, e.DEPT_ID, e.POSITION_ID, e.BIRTH_DATE, e.HIRE_DATE,
           DATEDIFF('year', e.BIRTH_DATE, CURRENT_DATE()) AS AGE,
           p.GRADE AS CURRENT_GRADE
    FROM HR_ANALYTICS.STAGING.EMPLOYEES e
    LEFT JOIN HR_ANALYTICS.STAGING.POSITIONS p ON e.POSITION_ID = p.POSITION_ID
    WHERE e.STATUS = 'active'
),
emp_skills AS (
    SELECT EMPLOYEE_ID, COUNT(DISTINCT SKILL_ID) AS SKILL_CNT,
           LISTAGG(SKILL_ID, ',') AS SKILL_IDS
    FROM HR_ANALYTICS.STAGING.EMPLOYEE_SKILLS
    GROUP BY EMPLOYEE_ID
),
dept_skills AS (
    SELECT e.DEPT_ID, COUNT(DISTINCT es.SKILL_ID) AS DEPT_SKILL_CNT,
           LISTAGG(DISTINCT es.SKILL_ID, ',') AS DEPT_SKILL_IDS
    FROM HR_ANALYTICS.STAGING.EMPLOYEE_SKILLS es
    JOIN HR_ANALYTICS.STAGING.EMPLOYEES e ON es.EMPLOYEE_ID = e.EMPLOYEE_ID
    GROUP BY e.DEPT_ID
),
career AS (
    SELECT EMPLOYEE_ID, COUNT(*) AS TRANSFER_CNT,
           AVG(PERFORMANCE_AFTER) AS AVG_PERF_AFTER
    FROM HR_ANALYTICS.STAGING.CAREER_HISTORY WHERE TRANSFER_TYPE != 'hire'
    GROUP BY EMPLOYEE_ID
),
dept_tenure AS (
    SELECT DEPT_ID, AVG(DATEDIFF('month', HIRE_DATE, CURRENT_DATE())) AS AVG_TENURE
    FROM HR_ANALYTICS.STAGING.EMPLOYEES WHERE STATUS='active'
    GROUP BY DEPT_ID
),
eval_numbered_tf AS (
    SELECT EMPLOYEE_ID, SCORE,
           ROW_NUMBER() OVER (PARTITION BY EMPLOYEE_ID ORDER BY PERIOD) AS RN
    FROM HR_ANALYTICS.STAGING.EVALUATIONS
),
eval_trend AS (
    SELECT EMPLOYEE_ID, REGR_SLOPE(SCORE, RN) AS TREND
    FROM eval_numbered_tf GROUP BY EMPLOYEE_ID
),
sent_numbered_tf AS (
    SELECT oa.EMPLOYEE_ID, oa.SENTIMENT_SCORE,
           ROW_NUMBER() OVER (PARTITION BY oa.EMPLOYEE_ID ORDER BY n.NOTE_DATE) AS RN
    FROM HR_ANALYTICS.STAGING.ONEONONE_ANALYSIS oa
    JOIN HR_ANALYTICS.STAGING.ONE_ON_ONE_NOTES n ON oa.NOTE_ID = n.NOTE_ID
),
sent_trend AS (
    SELECT EMPLOYEE_ID, REGR_SLOPE(SENTIMENT_SCORE, RN) AS TREND
    FROM sent_numbered_tf GROUP BY EMPLOYEE_ID
),
vacant_positions AS (
    SELECT p.POSITION_ID, p.DEPT_ID, p.GRADE
    FROM HR_ANALYTICS.STAGING.POSITIONS p
    WHERE p.IS_VACANT = TRUE
    ORDER BY p.POSITION_ID  -- 実行ごとに対象のポストが変わらないように固定
    LIMIT 50
),
dept_culture AS (
    SELECT DEPT_ID, AVG_SENTIMENT FROM DEPT_CULTURE_VECTORS
),
emp_dept_sent AS (
    SELECT e.EMPLOYEE_ID, dc.AVG_SENTIMENT AS EMP_DEPT_SENT
    FROM HR_ANALYTICS.STAGING.EMPLOYEES e
    LEFT JOIN dept_culture dc ON e.DEPT_ID = dc.DEPT_ID
)
SELECT
    ae.EMPLOYEE_ID,
    vp.DEPT_ID,
    vp.POSITION_ID,
    LEAST(COALESCE(esk.SKILL_CNT, 0)::FLOAT / GREATEST(COALESCE(dsk.DEPT_SKILL_CNT, 1), 1), 1.0),
    GREATEST(COALESCE(dsk.DEPT_SKILL_CNT, 0) - COALESCE(esk.SKILL_CNT, 0), 0),
    COALESCE(c.TRANSFER_CNT, 0),
    COALESCE(dt.AVG_TENURE, 24),
    COALESCE(c.AVG_PERF_AFTER, 3.0),
    COALESCE(et.TREND, 0.0),
    1.0 - ABS(COALESCE(eds.EMP_DEPT_SENT, 0) - COALESCE(dct.AVG_SENTIMENT, 0)),
    CASE WHEN ae.CURRENT_GRADE IS NULL OR vp.GRADE IS NULL THEN 0
         ELSE ABS(ASCII(LEFT(ae.CURRENT_GRADE, 1)) - ASCII(LEFT(vp.GRADE, 1))) END,
    ae.AGE,
    COALESCE(st.TREND, 0.0),
    CURRENT_TIMESTAMP()
FROM active_emps ae
CROSS JOIN vacant_positions vp
LEFT JOIN emp_skills esk ON ae.EMPLOYEE_ID = esk.EMPLOYEE_ID
LEFT JOIN dept_skills dsk ON vp.DEPT_ID = dsk.DEPT_ID
LEFT JOIN career c ON ae.EMPLOYEE_ID = c.EMPLOYEE_ID
LEFT JOIN dept_tenure dt ON vp.DEPT_ID = dt.DEPT_ID
LEFT JOIN eval_trend et ON ae.EMPLOYEE_ID = et.EMPLOYEE_ID
LEFT JOIN sent_trend st ON ae.EMPLOYEE_ID = st.EMPLOYEE_ID
LEFT JOIN emp_dept_sent eds ON ae.EMPLOYEE_ID = eds.EMPLOYEE_ID
LEFT JOIN dept_culture dct ON vp.DEPT_ID = dct.DEPT_ID
WHERE ae.DEPT_ID != vp.DEPT_ID
""").collect()
tf_count = session.sql("SELECT COUNT(*) AS C FROM TRANSFER_FIT_FEATURES").collect()[0]["C"]
print(f"  TRANSFER_FIT_FEATURES: {tf_count} rows")

# ============================================================================

print("\n完了!")
