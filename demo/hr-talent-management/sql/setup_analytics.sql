CREATE MASKING POLICY IF NOT EXISTS SALARY_MASK AS
    (val INTEGER) RETURNS INTEGER ->
    CASE
        WHEN CURRENT_ROLE() IN ('HR_ADMIN_ROLE', 'SYSADMIN', 'ACCOUNTADMIN')
            THEN val
        ELSE NULL
    END
COMMENT = 'Masks salary for non-admin roles';

CREATE MASKING POLICY IF NOT EXISTS EVAL_SCORE_MASK AS
    (val FLOAT) RETURNS FLOAT ->
    CASE
        WHEN CURRENT_ROLE() IN ('HR_ADMIN_ROLE', 'HR_MANAGER_ROLE', 'SYSADMIN', 'ACCOUNTADMIN')
            THEN val
        ELSE NULL
    END
COMMENT = 'Masks evaluation score for viewer roles';

CREATE MASKING POLICY IF NOT EXISTS EVAL_COMMENT_MASK AS
    (val VARCHAR) RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('HR_ADMIN_ROLE', 'HR_MANAGER_ROLE', 'SYSADMIN', 'ACCOUNTADMIN')
            THEN val
        ELSE '***'
    END
COMMENT = 'Masks evaluation comments for viewer roles';

CREATE MASKING POLICY IF NOT EXISTS PII_EMAIL_MASK AS
    (val VARCHAR) RETURNS VARCHAR ->
    CASE
        WHEN CURRENT_ROLE() IN ('HR_ADMIN_ROLE', 'SYSADMIN', 'ACCOUNTADMIN')
            THEN val
        ELSE REGEXP_REPLACE(val, '(.{2})(.*)(@.*)', '\\1***\\3')
    END
